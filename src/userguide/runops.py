"""runops — workflow stages 5–8 as local, read-only-or-local-write operations.

Launch  : prepare the run directory (Allrun + run manifest) — deterministic, nothing is submitted;
          submitting to a scheduler is an explicit user action, so the manifest carries the exact command.
Monitor : survey a run directory (frames per domain, first/last timestamp, output interval, restart files,
          rsl SUCCESS, newest-file age -> stall minutes). Local paths only, no ssh.
Verify  : frame-level acceptance: expected count, window endpoints, no duplicates/gaps at the interval,
          SUCCESS in rsl.error.0000 — the lightweight local sibling of `wrf_case verify-dir`.
Restart : restart is also compilation: find the latest wrfrst, build a restart override of the approved
          specification (run-control keys only) and re-emit; design fields cannot change because they are
          copied verbatim from experiment.yaml and the changed-key list is asserted.
"""

from __future__ import annotations

import datetime as dt
import re
from pathlib import Path

import yaml

from . import emit

FRAME_RE = re.compile(r"^wrfout_(d\d+)_(\d{4}-\d{2}-\d{2}_\d{2}:\d{2}:\d{2})$")
RST_RE = re.compile(r"^wrfrst_(d\d+)_(\d{4}-\d{2}-\d{2}_\d{2}:\d{2}:\d{2})$")

ALLRUN = """#!/bin/bash
# Generated by WRF-Agent (stage: Launch). Prepared, NOT submitted — see run_manifest.yaml.
# Adapt the scheduler section to the target platform; submission is an explicit user action.
set -euo pipefail
cd "$(dirname "$0")"

# 1) preprocessing is expected to be done (WPS + real) or add it here:
#    ./link_grib.csh ... ; ungrib.exe ; metgrid.exe ; real.exe

# 2) model run (local example; use your scheduler's submit wrapper on HPC)
#    n=30  # ranks
#    mpirun -n $n ./wrf.exe

# 3) acceptance: python3 - <<'PY' (frame check) — or `wrf_case verify-dir` where wrf-kit is installed
"""


def _y(p: Path):
    return yaml.safe_load(p.read_text(encoding="utf-8")) if p.exists() else None


def _w(p: Path, data) -> None:
    p.write_text(yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")


# --------------------------------------------------------------------------- Launch


def prepare_launch(case: Path) -> dict:
    manifest = _y(case / "build" / "emit_manifest.yaml")
    if not manifest or manifest.get("verdict") != "COMPLETE":
        return {"ok": False, "error": "emit manifest missing or INCOMPLETE — compile first"}
    run = case / "run"
    run.mkdir(parents=True, exist_ok=True)
    for f in ("namelist.wps", "namelist.input"):
        src, dst = case / "build" / f, run / f
        if not dst.exists() or dst.read_bytes() != src.read_bytes():
            dst.write_bytes(src.read_bytes())
    (run / "Allrun").write_text(ALLRUN, encoding="utf-8")
    rm = {
        "prepared_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "wrf_version": manifest.get("wrf_version"),
        "spec_sha256": manifest.get("spec_sha256"),
        "namelists": manifest["files"],
        "submitted": False,
        "note": "Prepared only. To submit, the user runs the scheduler command explicitly; "
                "WRF-Agent does not submit on its own.",
    }
    _w(run / "run_manifest.yaml", rm)
    return {"ok": True, "run_dir": str(run), "manifest": rm}


# --------------------------------------------------------------------------- Monitor


def survey(run_dir: Path) -> dict:
    frames: dict[str, list[str]] = {}
    rst: dict[str, list[str]] = {}
    newest = 0.0
    for p in sorted(run_dir.iterdir()) if run_dir.is_dir() else []:
        m, r = FRAME_RE.match(p.name), RST_RE.match(p.name)
        if m:
            frames.setdefault(m.group(1), []).append(m.group(2))
        elif r:
            rst.setdefault(r.group(1), []).append(r.group(2))
        if p.is_file():
            newest = max(newest, p.stat().st_mtime)
    rsl = run_dir / "rsl.error.0000"
    success = False
    if rsl.exists():
        try:  # restart-style runs keep SUCCESS mid-file: search the whole (bounded) log
            with rsl.open("rb") as fh:
                success = b"SUCCESS COMPLETE WRF" in fh.read(20 * 1024 * 1024)
        except OSError:
            success = False
    per_domain = {}
    for d, ts in frames.items():
        ts = sorted(ts)
        diffs = [(dt.datetime.strptime(b, "%Y-%m-%d_%H:%M:%S") - dt.datetime.strptime(a, "%Y-%m-%d_%H:%M:%S")
                  ).total_seconds() / 60 for a, b in zip(ts, ts[1:])]
        mode = max(set(diffs), key=diffs.count) if diffs else None
        per_domain[d] = {"frames": len(ts), "first": ts[0] if ts else None, "last": ts[-1] if ts else None,
                         "interval_min": mode, "gaps": sum(1 for x in diffs if mode and x != mode)}
    stall_min = round((dt.datetime.now().timestamp() - newest) / 60, 1) if newest else None
    state = ("finished" if success else
             "archived (long idle)" if stall_min is not None and stall_min > 30 * 24 * 60 else
             "stalled" if stall_min is not None and stall_min > 120 else
             "running-or-idle" if per_domain else "empty")
    return {"run_dir": str(run_dir), "domains": per_domain, "restart_files": {d: sorted(t) for d, t in rst.items()},
            "rsl_success": success, "newest_file_age_min": stall_min, "state": state}


# --------------------------------------------------------------------------- Verify


def verify(run_dir: Path, expect_frames: int | None = None, interval_min: float | None = None, start: str | None = None, end: str | None = None) -> dict:
    s = survey(run_dir)
    checks = [{"check": "explicit count, cadence and window", "ok": bool(expect_frames and interval_min and start and end)}]
    try:
        begin = dt.datetime.strptime(start, "%Y-%m-%d_%H:%M:%S")
        finish = dt.datetime.strptime(end, "%Y-%m-%d_%H:%M:%S")
        step = dt.timedelta(minutes=float(interval_min))
        valid = bool(expect_frames and step.total_seconds() > 0 and finish > begin and
                     (finish - begin).total_seconds() / step.total_seconds() + 1 == expect_frames)
    except (TypeError, ValueError):
        valid = False
    checks.append({"check": "consistent approved window", "ok": valid})
    checks.append({"check": "rsl SUCCESS (informational)", "ok": True,
                   "detail": "found" if s["rsl_success"] else "not present; frame criteria decide"})
    if not s["domains"]:
        checks.append({"check": "wrfout files", "ok": False, "detail": "no wrfout files"})
    else:
        for domain, data in sorted(s["domains"].items()):
            timestamps = sorted(p.name.split("_", 2)[2] for p in run_dir.iterdir()
                                if FRAME_RE.match(p.name) and p.name.startswith(f"wrfout_{domain}_"))
            expected = [(begin + i * step).strftime("%Y-%m-%d_%H:%M:%S")
                        for i in range(expect_frames)] if valid else []
            checks.append({"check": f"{domain} exact window/cadence/count", "ok": valid and timestamps == expected,
                           "detail": f"{len(timestamps)} frames, expected {expect_frames}"})
    verdict = "PASS" if all(c["ok"] for c in checks) else "FAIL"
    return {"run_dir": str(run_dir), "verdict": verdict, "checks": checks, "survey": s}


# --------------------------------------------------------------------------- Restart


RUN_CONTROL = {"input:restart", "input:restart_interval", "wps:start_date", "wps:end_date",
               "input:run_hours", "input:run_days"}


def restart_override(case: Path, run_dir: Path | None = None) -> dict:
    """Restart = recompilation with a run-control overlay; design fields are copied verbatim and the
    changed-key list is asserted to stay inside RUN_CONTROL."""
    run_dir = run_dir or (case / "run")
    s = survey(run_dir)
    latest = None
    for d, ts in s["restart_files"].items():
        cand = max(ts)
        if latest is None or cand > latest[1]:
            latest = (d, cand)
    if not latest:
        return {"ok": False, "error": f"no wrfrst files in {run_dir}"}
    dom, t = latest
    spec = _y(case / "experiment.yaml")
    if not spec:
        return {"ok": False, "error": "no approved experiment.yaml"}
    t0 = dt.datetime.strptime(t, "%Y-%m-%d_%H:%M:%S")
    end = dt.datetime.strptime(str(spec["design"]["wps:end_date"]["value"]
                                    if isinstance(spec["design"]["wps:end_date"], dict)
                                    else spec["design"]["wps:end_date"]), "%Y-%m-%d_%H:%M:%S")
    new_spec = {
        "wrf_version": spec.get("wrf_version"),
        "derived_from_spec_sha256": None,  # filled after emit manifest read below
        "design": dict(spec["design"]),
        "restart": {"from": f"wrfrst_{dom}_{t}", "resume_at": t,
                    "remaining_hours": round((end - t0).total_seconds() / 3600, 2)},
    }
    new_spec["design"]["wps:start_date"] = {"value": t, "reason": f"resume from latest restart point {dom} {t}"}
    new_spec["design"]["input:restart"] = {"value": ".true.", "reason": "restart run"}  # type: ignore[dict-item]
    changed = sorted(k for k in new_spec["design"]
                     if str(new_spec["design"][k]) != str(spec["design"].get(k)) and k not in RUN_CONTROL)
    if changed:  # design fields must not differ — construction guarantee
        return {"ok": False, "error": f"internal: design fields changed {changed}"}
    _w(case / "restart.yaml", new_spec)
    rep = emit.emit(new_spec, case / "build" / "restart", force=True)
    return {"ok": True, "restart": new_spec["restart"], "changed_design_fields": changed,
            "emit_verdict": rep["verdict"], "out": str(case / "build" / "restart")}
